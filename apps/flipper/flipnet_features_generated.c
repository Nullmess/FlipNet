const size_t	g_flipnet_features_count =
	sizeof(g_flipnet_features) / sizeof(g_flipnet_features[0]);

const t_flipnet_feature_definition	*flipnet_feature_definition_find(
			const char *service)
{
	size_t	index;

	if (!service)
		return (NULL);
	index = 0U;
	while (index < g_flipnet_features_count)
	{
		if (!strcmp(g_flipnet_features[index].id, service))
			return (&g_flipnet_features[index]);
		index++;
	}
	return (NULL);
}
